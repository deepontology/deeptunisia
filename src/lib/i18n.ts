const DICTS: Record<Locale, Dict> = { en, fr, ar };

/**
 * Translate. Falls back to English rather than showing a raw key, because a missing
 * string should degrade to readable text, not to debug output.
 */
export function translate(locale: Locale, key: string): string {
	return DICTS[locale][key] ?? DICTS.en[key] ?? key;
}

/**
 * A translated string with values substituted into it.
 *
 * Exists so that generated sentences — date ranges, durations, succession gaps — are
 * translated as WHOLE SENTENCES rather than assembled from fragments. Concatenation
 * produces wrong grammar in French and Arabic, and worse, it loses distinctions this
 * project depends on: "confirmed through Dec 2025, possibly later" is a different
 * claim from "ended Dec 2025", and `/now` splits its entire display on that difference.
 * A translator handed the pieces cannot see which is which; handed the sentence, they
 * can.
 *
 * Unknown placeholders are left in place rather than blanked, so a missing parameter
 * shows up as `{start}` in the interface instead of a plausible-looking half-sentence.
 * `scripts/test-i18n.ts` fails on any that survive to render.
 */
export function format(locale: Locale, key: string, params: Record<string, string | number> = {}): string {
	return translate(locale, key).replace(/\{(\w+)\}/g, (whole, name: string) =>
		name in params ? String(params[name]) : whole
	);
}

/**
 * Month and day names come from the platform, not from a table in this file.
 *
 * `formatDate` used to close over a hard-coded English `MONTHS` array and took no
 * locale at all, so every date on the site rendered in English inside the Arabic and
 * French interfaces — invisible to a key-coverage audit, which is why it survived.
 *
 * NUMERALS ARE LATIN IN ALL THREE LOCALES, INCLUDING ARABIC.
 *
 * `numberingSystem: 'latn'` is set explicitly rather than left to the default, which
 * for `ar` would be Eastern Arabic digits. Three reasons, and the first is structural:
 * every number in this product is tabular mono, and the Chronicle, Atlas and Rankings
 * depend on digits being identical widths — Eastern Arabic numerals in the mono stack
 * break that alignment. Second, the sources quote decree numbers and years in Latin
 * digits, and a year rendered ١٩٨٧ beside a decree citing 1987 invites the reader to
 * think they are two different things. Third, Latin digits are unremarkable in
 * Tunisian Arabic print.
 */
const dtf = new Map<string, Intl.DateTimeFormat>();

export function dateFormatter(locale: Locale, opts: Intl.DateTimeFormatOptions): Intl.DateTimeFormat {
	const key = locale + JSON.stringify(opts);
	let f = dtf.get(key);
	if (!f) {
		f = new Intl.DateTimeFormat(locale, { timeZone: 'UTC', numberingSystem: 'latn', ...opts });
		dtf.set(key, f);
	}
	return f;
}

/** Coverage per locale, published on the about page instead of quietly assumed. */
export function localeCoverage(locale: Locale): number {
	const total = Object.keys(en).length;
	const have = Object.keys(DICTS[locale]).length;
	return Math.round((have / total) * 100);
}

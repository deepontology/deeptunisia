/**
 * Interface localisation: Arabic, French, English.
 *
 * Scope, stated plainly rather than overclaimed: this covers the interface chrome —
 * navigation, controls, column headings, section titles, legends. Entity names,
 * titles and institutions come from the data, which carries Arabic and French forms
 * natively. Long-form analytical prose (methodology, hypothesis reasoning, era
 * theses) remains in English for now and is marked as such in the UI rather than
 * machine-translated, because a machine-translated epistemology page would
 * undermine the entire point of the project.
 *
 * Arabic drives `dir="rtl"` on the document. One deliberate exception: the time
 * axis continues to run left-to-right even in Arabic, because that is the
 * convention for charts and reversing it makes every timeline unreadable to people
 * who read charts in any language.
 */

export type Locale = 'en' | 'fr' | 'ar';

export const LOCALES: { id: Locale; label: string; native: string; dir: 'ltr' | 'rtl' }[] = [
	{ id: 'en', label: 'English', native: 'English', dir: 'ltr' },
	{ id: 'fr', label: 'French', native: 'Français', dir: 'ltr' },
	{ id: 'ar', label: 'Arabic', native: 'العربية', dir: 'rtl' }
];

export function dirFor(locale: Locale): 'ltr' | 'rtl' {
	return locale === 'ar' ? 'rtl' : 'ltr';
}


						{#each filteredSetB as i (i.id)}
							<Button
								variant="outline"
								size="xs"
								active={setB.includes(i.id)}
								tint={LAYER_COLOR[i.layer as Layer]}
								onclick={() => (setB = toggle(setB, i.id))}>{i.abbr ?? nameOf(i)}</Button
							>
						{/each}
					</div>
				</fieldset>
			</div>
		{:else}
			<fieldset>
				<legend>{t('investigate.subject')}</legend>
				<select bind:value={subject}>
					{#each [...ds.people].sort((a, b) => nameOf(a).localeCompare(nameOf(b))) as p (p.id)}
						<option value={p.id}>{nameOf(p)}</option>

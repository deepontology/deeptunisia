								<td class="inst">{nameOf(institutionById.get(p.institution))}</td>
								<td class="span mono">{describeInterval(p.interval)}</td>
								<td class="num mono">{durationLabel(p.years)}</td>
								<td>
									<Chip size="xs" tint={BASIS_COLOR[p.basis as Basis]}>{BASIS_SHORT[p.basis as Basis]}</Chip>
								</td>
							</tr>
						{/each}
					</tbody>
				</table>
			{/if}
		{:else if mode === 'crossings'}
			<h2>{format(app.locale, 'investigate.crossingsCount', { n: crossings.length })}</h2>
			<p class="note">{t('investigate.crossNote')}</p>
			{#if crossings.length === 0}
				<p class="empty">{t('investigate.crossEmpty')}</p>
			{:else}
				<div class="cross-list">
					{#each crossings as c (c.id)}
						<article>
							<header>
								<button class="cname" onclick={() => app.select(c.id)}>{entityName(c.id)}</button>
								<span class="mono ctotal">{durationLabel(c.years)} {t('investigate.total')}</span>
							</header>
							<div class="two">
								<div>
									<span class="eyebrow">{t('investigate.setA')}</span>
									<ul>
										{#each c.a as p (p.id)}
											<li>
												<strong>{p.roleTitle}</strong>
												<span class="mono">{describeInterval(p.interval)}</span>
												<SourceList ids={p.sources} compact />
											</li>
										{/each}
									</ul>
								</div>
								<div>
									<span class="eyebrow">{t('investigate.setB')}</span>
									<ul>
										{#each c.b as p (p.id)}
											<li>
												<strong>{p.roleTitle}</strong>
												<span class="mono">{describeInterval(p.interval)}</span>
												<SourceList ids={p.sources} compact />
											</li>
										{/each}
									</ul>
								</div>
							</div>
						</article>
					{/each}
				</div>
			{/if}
		{:else}
			<h2>{format(app.locale, 'investigate.connCount', { name: entityName(subject), n: connections.rels.length, m: connections.posts.length })}</h2>
			{#if connections.posts.length}
				<h3>{t('investigate.postsInPeriod')}</h3>
				<ul class="plain">
					{#each connections.posts as p (p.id)}
						<li>
							<strong>{p.roleTitle}</strong>
							<span class="mono">{describeInterval(p.interval)}</span>
							<Chip size="xs" tint={BASIS_COLOR[p.basis as Basis]}>{BASIS_SHORT[p.basis as Basis]}</Chip>
						</li>
					{/each}
				</ul>
			{/if}
			{#if connections.rels.length}
				<h3>{t('investigate.connections')}</h3>
				<ul class="plain">
					{#each connections.rels as r (r.id)}
						{@const other = r.from === subject ? r.to : r.from}
						<li>
							<button onclick={() => app.select(other)}>{entityName(other)}</button>
							<span class="rtype">{relLabel(r.type)}</span>
							<Chip size="xs" tint={BASIS_COLOR[r.basis as Basis]}>{BASIS_SHORT[r.basis as Basis]}</Chip>
							{#if relKind(r.type) !== 'documented' && r.attributed_to}
								<span class="attrib">{format(app.locale, 'investigate.claimedBy', { who: r.attributed_to })}</span>
							{/if}
							<p class="rdesc">{r.description}</p>
							<SourceList ids={r.sources} compact />
						</li>
					{/each}
				</ul>
			{/if}
		{/if}
	</div>
</div>


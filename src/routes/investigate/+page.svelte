					{#each institutions as i (i.id)}
						<option value={i.id}>{nameOf(i)}</option>
					{/each}
				</select>
			</fieldset>
		{/if}
	</div>

	<div class="results">
		{#if mode === 'officeholders'}
			<h2>
				{format(app.locale, 'investigate.holdersCount', {
					n: officeholders.length,

			</h2>
			{#if officeholders.length === 0}
				<p class="empty">{t('investigate.empty')}</p>
			{:else}
				<table>
					<thead>
						<tr>
							<th>{t('investigate.person')}</th><th>{t('investigate.post')}</th><th>{t('investigate.institution')}</th><th>{t('investigate.span')}</th><th class="num">{t('investigate.held')}</th
							><th>{t('investigate.basis')}</th>

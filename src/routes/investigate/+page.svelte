<script lang="ts">
	import { app } from '$lib/state.svelte';
	import SourceList from '$lib/components/SourceList.svelte';
	import Button from '$lib/ui/Button.svelte';
	import Chip from '$lib/ui/Chip.svelte';
	import Input from '$lib/ui/Input.svelte';
	import {
		BASIS_COLOR,
		BASIS_SHORT,
		LAYER_COLOR,
		ds,
		institutionById,
		meetsBasis,
		overlaps,
		personById,
		relKind,
		relationshipsByEntity,
		type Basis,
		type Layer
	} from '$lib/model';
	import { describeInterval, durationLabel, nameOf, entityName, relLabel, t } from '$lib/t.svelte';
	import { format } from '$lib/i18n';

	/**
	 * Structured investigative search.
	 *
	 * The important design constraint: answers are computed by traversing the dataset,
	 * not generated by a language model. Every row is a record with sources attached.
	 * An AI layer can sit on top of this later to phrase the question, but it must not
	 * be what produces the answer, or the whole evidentiary architecture is decorative.
	 */

	type Mode = 'officeholders' | 'crossings' | 'connections';

	let mode = $state<Mode>('officeholders');
	let instFilter = $state<string[]>(['ministry-interior']);
	let layerFilter = $state<Layer | 'all'>('all');
	let fromYear = $state(1987);
	let toYear = $state(2011);
	let setA = $state<string[]>(['armed-forces', 'military-security']);
	let setB = $state<string[]>(['presidential-security', 'presidency']);
	let subject = $state('ben-ali');
	let instQuery = $state('');
	let setAQuery = $state('');
	let setBQuery = $state('');

	const institutions = $derived([...ds.institutions].sort((a, b) => a.order - b.order));

	function matchesFilter(inst: (typeof institutions)[number], q: string): boolean {
		const needle = q.trim().toLowerCase();
		if (!needle) return true;
		const hay = `${nameOf(inst)} ${inst.abbr ?? ''}`.toLowerCase();
		return hay.includes(needle);
	}

	const filteredInst = $derived(institutions.filter((i) => matchesFilter(i, instQuery)));
	const filteredSetA = $derived(institutions.filter((i) => matchesFilter(i, setAQuery)));
	const filteredSetB = $derived(institutions.filter((i) => matchesFilter(i, setBQuery)));

	const range = $derived<[number, number]>([
		Date.UTC(Math.min(fromYear, toYear), 0, 1),
		Date.UTC(Math.max(fromYear, toYear), 11, 31)
	]);

	const eligible = $derived(
		ds.positions.filter(
			(p) =>
				meetsBasis(p.basis as Basis, app.basisFloor) &&
				app.activeLayers.has(p.layer as Layer) &&
				(layerFilter === 'all' || p.layer === layerFilter)
		)
	);

	// --- Query 1: officeholders in an institution within a window --------------

	const officeholders = $derived.by(() => {
		const rows = eligible.filter(
			(p) =>
				(instFilter.length === 0 || instFilter.includes(p.institution)) &&
				overlaps(p.interval, range[0], range[1])
		);
		return rows.sort(
			(a, b) => b.authority - a.authority || a.interval.startEarliest - b.interval.startEarliest
		);
	});

	// --- Query 2: people who served in BOTH sets ------------------------------
	//
	// This is the query that finds bridge figures, and it is the one the underlying
	// research kept reaching for by hand.

	const crossings = $derived.by(() => {
		const inA = new Map<string, typeof eligible>();
		const inB = new Map<string, typeof eligible>();
		for (const p of eligible) {
			if (!overlaps(p.interval, range[0], range[1])) continue;
			if (setA.includes(p.institution)) {
				inA.set(p.holder, [...(inA.get(p.holder) ?? []), p]);
			}
			if (setB.includes(p.institution)) {
				inB.set(p.holder, [...(inB.get(p.holder) ?? []), p]);
			}
		}
		const both = [...inA.keys()].filter((id) => inB.has(id));
		return both
			.map((id) => ({
				id,
				a: inA.get(id)!,
				b: inB.get(id)!,
				years: [...inA.get(id)!, ...inB.get(id)!].reduce((s, p) => s + p.years, 0)
			}))
			.sort((x, y) => y.years - x.years);
	});

	// --- Query 3: everything connected to one entity in a window --------------

	const connections = $derived.by(() => {
		const rels = (relationshipsByEntity.get(subject) ?? []).filter(
			(r) =>
				meetsBasis(r.basis as Basis, app.basisFloor) &&
				(r.interval.raw.start === null || overlaps(r.interval, range[0], range[1]))
		);
		const posts = eligible.filter(
			(p) => p.holder === subject && overlaps(p.interval, range[0], range[1])
		);
		return { rels, posts };
	});

	const PRESETS: { label: string; run: () => void }[] = [
		{
			label: t('investigate.preset.1'),
			run: () => {
				mode = 'officeholders';
				instFilter = ['ministry-interior', 'national-security', 'national-guard'];
				fromYear = 1987;
				toYear = 2011;
				layerFilter = 'all';
			}
		},
		{
			label: t('investigate.preset.2'),
			run: () => {
				mode = 'crossings';
				setA = ['armed-forces', 'land-forces', 'navy', 'air-force', 'military-security', 'anrsd'];
				setB = ['presidency', 'presidential-security', 'presidential-security-adviser'];
				fromYear = 1956;
				toYear = 2026;
			}
		},
		{
			label: t('investigate.preset.3'),
			run: () => {
				mode = 'crossings';
				setA = ['mabrouk-group', 'elloumi-group', 'nessma-tv', 'biat', 'trabelsi-network'];
				setB = ['head-of-government', 'presidency', 'nidaa-tounes', 'qalb-tounes'];
				fromYear = 1987;
				toYear = 2026;
			}
		},
		{
			label: t('investigate.preset.4'),
			run: () => {
				mode = 'officeholders';
				instFilter = ['national-security', 'national-guard', 'ministry-interior'];
				fromYear = 2021;
				toYear = 2026;
			}
		},
		{
			label: t('investigate.preset.5'),
			run: () => {
				mode = 'connections';
				subject = 'ben-ali';
				fromYear = 1956;
				toYear = 2026;
			}
		}
	];

	function toggle(list: string[], id: string): string[] {
		return list.includes(id) ? list.filter((x) => x !== id) : [...list, id];
	}
</script>

